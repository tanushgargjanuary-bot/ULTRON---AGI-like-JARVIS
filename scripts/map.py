"""scripts/map.py — write the module map from the code, not from memory.

A hand-written architecture document drifts within a week. This one is generated:
it reads the first line of every module's docstring, counts the lines, and finds
the test file that covers it. Run it after adding a module:

    python scripts\\map.py            # prints the map
    python scripts\\map.py --write    # also writes docs/MAP.md

It also fails, with exit code 1, when it finds a module with no docstring or a
module with no test — because those are the two ways a codebase stops being
readable, and both are cheap to fix.
"""

from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGES = ("core", "custom_jarvis", "plugins", "actions", "providers", "dashboard",
            "memory", "scripts", "tests")

# The packages this project owns and can fix today. The others are the upstream
# MARK application, kept as it arrived: reporting them is useful, failing the
# build on them would be blaming someone else's code for its own age.
STRICT = {"custom_jarvis", "plugins", "core"}

# Modules that arrived with the upstream MARK application and are still only
# exercised through the UI and scripts/verify_all.py. They are listed so the gap
# is visible; the check fails only when a module is added WITHOUT a test, which
# is the mistake this tool exists to catch.
KNOWN_GAPS = {
    "core/_smoke_harness.py", "core/audio_devices.py", "core/avatar_mesh.py",
    "core/code_checks.py", "core/llm_client.py", "core/platform_support.py",
    "core/stt.py", "core/tts.py", "core/ui_browser.py", "core/viseme.py",
    "core/wake_word.py",
}


def summary(path: Path) -> str:
    """The first line of the module docstring, or an empty string."""
    try:
        tree = ast.parse(path.read_text(encoding="utf-8", errors="replace"))
    except (OSError, SyntaxError):
        return ""
    text = ast.get_docstring(tree) or ""
    return text.strip().splitlines()[0].strip() if text.strip() else ""


def modules():
    for folder in PACKAGES:
        base = ROOT / folder
        if not base.is_dir():
            continue
        for path in sorted(base.glob("*.py")):
            if path.name == "__init__.py" or path.name.startswith("_"):
                continue
            yield folder, path


def tests_index() -> dict[str, list[str]]:
    """module stem -> the test files that name it, by word, anywhere in the text.

    Matching the file name alone was wrong: most tests import the module inside a
    test method, so `test_web_platforms.py` names `github_tool` and would never
    have been counted.
    """
    stems = {path.stem for _folder, path in modules()}
    index: dict[str, list[str]] = {}
    for path in sorted((ROOT / "tests").glob("test_*.py")):
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for stem in stems:
            if re.search(rf"\b{re.escape(stem)}\b", text):
                index.setdefault(stem, []).append(path.stem)
    return index


def covered(module: str, package: str, index: dict[str, list[str]]) -> str:
    """The test files that name this module."""
    hits = list(index.get(module, []))
    return ", ".join(sorted(set(hits)))


def report() -> tuple[str, list[str]]:
    index = tests_index()
    lines = ["# Module map", "",
             "Generated by `python scripts/map.py --write`. Do not edit by hand;",
             "edit the module docstring instead and run it again.", ""]
    problems: list[str] = []
    inherited: list[str] = []
    for folder in PACKAGES:
        rows = [(path, summary(path)) for name, path in modules() if name == folder]
        if not rows:
            continue
        total = sum(len(path.read_text(encoding="utf-8", errors="replace").splitlines())
                    for path, _ in rows)
        lines.append(f"## `{folder}/` — {len(rows)} modules, {total:,} lines")
        lines.append("")
        lines.append("| Module | Lines | What it is | Test |")
        lines.append("|---|---|---|---|")
        for path, text in rows:
            count = len(path.read_text(encoding="utf-8", errors="replace").splitlines())
            gaps = []
            if not text:
                gaps.append("no docstring")
            test = covered(path.stem, folder, index)
            if folder not in ("scripts", "tests") and not test:
                gaps.append("no test that names it")
            for gap in gaps:
                known = f"{folder}/{path.name}" in KNOWN_GAPS
                (inherited if known or folder not in STRICT else problems).append(
                    f"{folder}/{path.name}: {gap}")
            lines.append(f"| `{path.name}` | {count:,} | {text or '**no docstring**'} "
                         f"| {test or '—'} |")
        lines.append("")
    if inherited:
        lines.append("## Inherited, and reported not fixed")
        lines.append("")
        lines.append("Upstream MARK modules with no docstring or no test here. They are "
                     "listed so the gap is visible, not hidden.")
        lines.append("")
        for line in inherited:
            lines.append(f"- {line}")
        lines.append("")
    return "\n".join(lines), problems


def main(argv: list[str]) -> int:
    text, problems = report()
    print(text)
    if "--write" in argv:
        target = ROOT / "docs" / "MAP.md"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text + "\n", encoding="utf-8")
        print(f"written: {target.relative_to(ROOT)}")
    if problems:
        print("\nORGANISATION GAPS")
        for line in problems:
            print(f"  · {line}")
        return 1
    print("\nEvery module has a docstring and a test that names it.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
