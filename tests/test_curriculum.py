class TheShelf(unittest.TestCase):
    def test_the_file_is_sound(self):
        self.assertEqual(curriculum.problems(), [])

    def test_every_subject_the_owner_named_is_here(self):
        held = {row["short"] for row in curriculum.subjects()}
        for short in WANTED:
            with self.subTest(subject=short):
                self.assertIn(short, held)

    def test_every_subject_has_five_units_of_topics(self):
        for row in curriculum.subjects():
            with self.subTest(subject=row["short"]):
                self.assertEqual(len(row["units"]), 5)
                for unit in row["units"]:
                    self.assertTrue(unit["topics"], f"{row['short']} is missing topics")
                    self.assertTrue(unit["title"])

    def test_the_topics_are_topics_and_not_summaries(self):
        # A topic is a phrase a student would find in the syllabus, not a paragraph.
        for row in curriculum.subjects():
            for unit in row["units"]:
                for topic in unit["topics"]:
                    self.assertLess(len(topic), 120, topic)
                    self.assertGreater(len(topic), 3, topic)

    def test_course_codes_are_unique(self):
        codes = [row["code"] for row in curriculum.subjects()]
        self.assertEqual(len(codes), len(set(codes)))

    def test_every_subject_says_where_its_syllabus_came_from(self):
        for row in curriculum.subjects():
            with self.subTest(subject=row["short"]):
                self.assertTrue(row["syllabus"])
                self.assertGreater(len(row["syllabus"]), 20)

    def test_the_four_subjects_from_his_pdf_say_so(self):
        for code in ("BCS501", "BCAI501", "BCS503", "BCAI601"):
            row = curriculum.subject(code)
            self.assertIn("PDF", row["syllabus"], f"{code} does not name its source")

    def test_the_owner_s_own_phrases_survive(self):
        # If these ever vanish, the file was regenerated by something that guessed.
        dbms = " ".join(curriculum.plan("dbms"))
        daa = " ".join(curriculum.plan("daa"))
        ai = " ".join(curriculum.plan("ai"))
        for phrase in ("BCNF", "Lossless join decomposition", "Deadlock handling"):
            self.assertIn(phrase, dbms)
        for phrase in ("Fibonacci heaps", "Branch and bound", "NP-completeness"):
            self.assertIn(phrase, daa)
        for phrase in ("Alpha-beta pruning", "Unification", "Constraint propagation"):
            self.assertIn(phrase, ai)


class TheReading(unittest.TestCase):
    def test_every_subject_has_all_three_levels(self):
        for row in curriculum.subjects():
            levels = {item["level"] for item in row["ladder"]}
