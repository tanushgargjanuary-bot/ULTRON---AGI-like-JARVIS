"""The syllabus Ultron holds, and the four things that make it usable.

    it is complete     eight subjects, five units each, topics that a student can
                       check against the university's own page;
    it is answerable   a spoken name finds the subject: 'dbms', 'BCS501', 'the DBMS
                       syllabus';
    it is ordered      a plan that follows the course, and a 'next' that only moves
                       when the owner says a topic is done;
    it is honest       every subject says where its syllabus came from, and every
                       reading link was opened before it was written down.

Progress is written to a throwaway settings file, so a test run never touches the
owner's real progress.
"""

