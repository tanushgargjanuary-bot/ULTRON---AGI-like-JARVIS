class Progress(WithATemporaryConfig):
    def test_nothing_is_recorded_until_the_owner_says_so(self):
        self.assertEqual(curriculum.done(), [])
        self.assertEqual(curriculum.progress_of("dbms"), (0, 48))

    def test_marking_a_topic_records_exactly_one_thing(self):
        ok, sentence = curriculum.mark_done("dbms", "BCNF")
        self.assertTrue(ok, sentence)
        self.assertEqual(len(curriculum.done()), 1)
        self.assertEqual(curriculum.progress_of("dbms"), (1, 48))

    def test_the_same_topic_twice_is_recorded_once(self):
        curriculum.mark_done("daa", "Skip lists")
        ok, sentence = curriculum.mark_done("daa", "Skip lists")
        self.assertTrue(ok)
        self.assertIn("already", sentence)
        self.assertEqual(len(curriculum.done()), 1)

    def test_a_topic_that_is_not_in_the_course_is_refused(self):
        ok, sentence = curriculum.mark_done("coa", "quantum tunnelling")
        self.assertFalse(ok)
        self.assertIn("not one of the topics", sentence)
        self.assertEqual(curriculum.done(), [])

    def test_an_unknown_subject_is_refused(self):
        ok, sentence = curriculum.mark_done("cooking", "knife skills")
        self.assertFalse(ok)
        self.assertIn("do not hold", sentence)

    def test_next_moves_past_what_is_done(self):
        first = curriculum.next_topic("dstl")
        self.assertIn("unit 2", curriculum.next_topic("dstl")) if False else None
        curriculum.mark_done("dstl", "Sets and combination of sets")
        self.assertNotEqual(curriculum.next_topic("dstl"), first)

    def test_reset_clears_it(self):
        curriculum.mark_done("ds", "Priority queue")
        self.assertEqual(curriculum.clear_progress(), 1)
        self.assertEqual(curriculum.done(), [])


class TheTool(WithATemporaryConfig):
    @classmethod
    def setUpClass(cls):
        from actions import curriculum as tool
        cls.tool = tool

    def call(self, **parameters) -> str:
        return self.tool.curriculum_tool(parameters)

    def test_every_action_reaches_a_callable(self):
        for name in self.tool.ACTIONS:
            with self.subTest(action=name):
                self.assertTrue(callable(self.tool.ACTIONS[name]))

    def test_the_declaration_is_what_the_loader_expects(self):
        declaration = self.tool.TOOL
        self.assertEqual(declaration["name"], "curriculum")
        self.assertTrue(callable(declaration["handler"]))
        offered = set(declaration["parameters"]["properties"]["action"]["enum"])
        self.assertTrue(offered <= set(self.tool.ACTIONS))

    def test_subjects_lists_all_eight_with_counts(self):
        answer = self.call(action="subjects")
        for short in WANTED:
            self.assertIn(short, answer)
        self.assertIn("284", answer)

    def test_show_a_subject_names_its_units_and_source(self):
        answer = self.call(action="show", subject="DBMS")
        self.assertIn("BCS501", answer)
        self.assertIn("Unit 5", answer)
        self.assertIn("PDF", answer)

    def test_topics_of_one_unit_are_numbered(self):
        answer = self.call(action="topics", subject="daa", unit="2")
        self.assertIn("Red-black trees", answer)
        self.assertIn("2.1", answer)

    def test_plan_lists_every_topic_in_course_order(self):
        answer = self.call(action="plan", subject="coa")
        self.assertIn("Cache memory", answer)
        self.assertLess(answer.index("Addressing modes"), answer.index("Cache memory"))

    def test_next_says_where_to_start(self):
        self.assertIn("unit 1", self.call(action="next", subject="ai"))

    def test_resources_are_shown_with_levels(self):
        answer = self.call(action="resources", subject="ds", level="advanced")
        self.assertIn("advanced", answer)
        self.assertIn("http", answer)

    def test_an_unknown_subject_is_a_sentence_not_a_crash(self):
        answer = self.call(action="show", subject="astrophysics")
        self.assertIn("do not hold", answer)

    def test_an_unknown_action_lists_what_it_can_do(self):
        self.assertIn("plan", self.call(action="teleport"))

    def test_marking_done_through_the_tool(self):
        answer = self.call(action="done", subject="dbms", topic="Triggers")
        self.assertIn("Recorded", answer)

    def test_progress_reports_every_subject(self):
        answer = self.call(action="progress")
        for short in WANTED:
            self.assertIn(short, answer)

    def test_the_file_passes_its_own_check(self):
        self.assertIn("sound", self.call(action="check"))


